class _Row(dict):
    """Строка результата: и row["col"], и row[0] (замена sqlite3.Row)."""

    def __init__(self, cols, values):
        super().__init__(zip(cols, values))
        self._values = tuple(values)

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)

    def __iter__(self):  # tuple-распаковка: for _id, title, ... in rows
        return iter(self._values)


def _pg_row_factory(cursor):
    if cursor.description is None:  # INSERT/UPDATE/DDL без RETURNING
        return lambda values: None
    cols = [d.name for d in cursor.description]

    def make(values):
        return _Row(cols, values)

    return make


class _SqliteCursor:
    def __init__(self, cur):
        self._c = cur

    def execute(self, sql, params=()):
        return self._c.execute(sql.replace("%s", "?"), params)

    def executemany(self, sql, seq):
        return self._c.executemany(sql.replace("%s", "?"), seq)

    def __getattr__(self, name):
        return getattr(self._c, name)


class _SqliteConn:
    """sqlite3-коннект в PG-диалекте: %s → ?, transaction() как у psycopg."""

    def __init__(self, conn):
        self._c = conn

    def execute(self, sql, params=()):
        return self._c.execute(sql.replace("%s", "?"), params)

    def executemany(self, sql, seq):
        return self._c.executemany(sql.replace("%s", "?"), seq)

    def cursor(self):
        return _SqliteCursor(self._c.cursor())

    def commit(self):
        return self._c.commit()

    def rollback(self):
        return self._c.rollback()

    def close(self):
        return self._c.close()

    @contextmanager
    def transaction(self):
        with self._c:  # sqlite3: успех → commit, исключение → rollback
            yield

    def __getattr__(self, name):
        return getattr(self._c, name)


def executemany(conn, sql, seq):
    """psycopg3 держит executemany на курсоре; sqlite — на коннекте."""
    return conn.cursor().executemany(sql, seq)


def _pg_connect(url):
    # autocommit: как sqlite с явными commit() — проще всего перенести логику;
    # prepare_threshold=None — никаких prepared statements (pgbouncer transaction
    # mode не гарантирует их между транзакциями; 0 означало бы «готовить всегда»).
    conn = psycopg.connect(url, row_factory=_pg_row_factory, autocommit=True)
    conn.prepare_threshold = None
    return conn


def _run_schema(conn, schema):
    for stmt in schema.split(";"):
        if stmt.strip():
            conn.execute(stmt)


def _migrate(conn) -> None:
    """Идемпотентные миграции поверх свежей схемы (11d/D45: interests_text,
    iter-14: items.text — колонки отсутствуют только у БД, созданных до
    соответствующей итерации)."""
    try:
        conn.execute("ALTER TABLE users ADD COLUMN interests_text TEXT")
    except (sqlite3.OperationalError, pg_errors.DuplicateColumn):
        pass  # колонка уже есть (SCHEMA_* для свежих БД или прошлый запуск)
    try:
        conn.execute("ALTER TABLE items ADD COLUMN text TEXT")
    except (sqlite3.OperationalError, pg_errors.DuplicateColumn):
        pass
    try:
        conn.execute("ALTER TABLE items ADD COLUMN enriched INTEGER DEFAULT 0")
    except (sqlite3.OperationalError, pg_errors.DuplicateColumn):
        pass  # iter-14b: 0 — попытка не была, 1 — текст уже есть, 2 — попытка завершена
    try:
        conn.execute("ALTER TABLE items ADD COLUMN gist TEXT")
    except (sqlite3.OperationalError, pg_errors.DuplicateColumn):
        pass  # iter-14c: LLM-выжимка; NULL — не обрабатывалось, '' — пустышка/сбой


def connect(path=None):
    """Выбор движка: BOT_DB_PATH/файл → sqlite; SUPABASE_DB_URL → PG;
    ':memory:' (тесты) → PG во временной схеме, если задан BOT_TEST_PG_URL."""
    if path == ":memory:" and config.TEST_PG_URL:
        conn = _pg_connect(config.TEST_PG_URL)
        schema = f"t_{uuid.uuid4().hex}"
        conn.execute(f'CREATE SCHEMA "{schema}"')
        conn.execute(f'SET search_path TO "{schema}"')
        _run_schema(conn, SCHEMA_PG)
        _migrate(conn)
        return conn
    if path is None and config.SUPABASE_DB_URL and not os.environ.get("BOT_DB_PATH"):
        conn = _pg_connect(config.SUPABASE_DB_URL)
        _run_schema(conn, SCHEMA_PG)
        _migrate(conn)
        return conn
    # check_same_thread=False: хендлеры зовут БД через asyncio.to_thread (последовательно)
    conn = sqlite3.connect(path or config.DB_PATH, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys=ON")
    conn.executescript(SCHEMA_SQLITE)
    _migrate(conn)
    return _SqliteConn(conn)


def now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def is_broken(conn) -> bool:
    """Мёртвое соединение (М2: PG-коннект к Supabase после обрыва сети
    вечно отдаёт «another command is already in progress» — инцидент
    2026-09-14). sqlite — файл на диске, ломаться нечему."""
    if conn is None or isinstance(conn, _SqliteConn):
        return False
    try:
        conn.execute("SELECT 1").fetchone()
        return False
    except Exception:
        return True


def reconnect(conn):
    """Битое PG-соединение → свежее (вызывает slots_loop при сбое тика).
    Не бросает: если сеть ещё недоступна, вернёт старое — повтор на
    следующем тике (20 с)."""
    if not is_broken(conn):
        return conn
    try:
        conn.close()
    except Exception:
        pass
    try:
        return connect()
    except Exception:
        return conn


def minus_iso(now: str, hours: int) -> str:
    """ISO-метка на `hours` часов раньше данной (для периода сводки, D9)."""
    moment = datetime.fromisoformat(now.replace("Z", "+00:00")) - timedelta(hours=hours)
    return moment.strftime("%Y-%m-%dT%H:%M:%SZ")


def insert_item(conn, source_id, url, title, published, text=None) -> bool:
    """Вставка элемента с дедупом UNIQUE(source_id, url_hash) (R5/D19) и
    надгробием seen_hashes (11e/D47): удалённая по retention запись фида
    не вставляется повторно — False (как дубль). text — полный текст пункта
    (iter-14, уровень 1: TG-пост/текст фида)."""
    digest = url_hash(url, title)
    if conn.execute(
        "SELECT 1 FROM seen_hashes WHERE source_id=%s AND url_hash=%s",
        (source_id, digest),
    ).fetchone():
        return False
    try:
        conn.execute(
            "INSERT INTO items (source_id, url, title, text, enriched, published, fetched_at, url_hash)"
            " VALUES (%s, %s, %s, %s, %s, %s, %s, %s)",
            (source_id, url, title, text, 1 if text else 0,
             published or now_iso(), now_iso(), digest),
        )
        return True
    except (sqlite3.IntegrityError, pg_errors.UniqueViolation):
        return False


def ensure_bootstrap(conn, feed_url) -> int:
    """И1: служебный пользователь chat_id=0 и один захардкоженный RSS-источник."""
    conn.execute(
        "INSERT INTO users (chat_id, created_at) VALUES (%s, %s)"
        " ON CONFLICT (chat_id) DO NOTHING",
        (0, now_iso()),
    )
    conn.execute(
        "INSERT INTO sources (chat_id, kind, url, title, origin, added_at)"
        " VALUES (0, 'rss', %s, 'Bootstrap feed', 'manual', %s)"
        " ON CONFLICT (chat_id, kind, url) DO NOTHING",
        (feed_url, now_iso()),
    )
    conn.commit()
    row = conn.execute(
        "SELECT id FROM sources WHERE chat_id=0 AND kind='rss' AND url=%s", (feed_url,)
    ).fetchone()
    return row[0]


