def ensure_bootstrap(conn, feed_url) -> int:
    """И1: служебный пользователь chat_id=0 и один захардкоженный RSS-источник."""
    conn.execute(
        "INSERT INTO users (chat_id, created_at) VALUES (%s, %s)"
        " ON CONFLICT (chat_id) DO NOTHING",
        (0, now_iso()),
    )
    conn.execute(
        "INSERT INTO sources (chat_id, kind, url, title, origin, added_at)"
        " VALUES (0, 'rss', %s, 'Bootstrap feed', 'manual', %s)"
        " ON CONFLICT (chat_id, kind, url) DO NOTHING",
        (feed_url, now_iso()),
    )
    conn.commit()
    row = conn.execute(
        "SELECT id FROM sources WHERE chat_id=0 AND kind='rss' AND url=%s", (feed_url,)
    ).fetchone()
    return row[0]


