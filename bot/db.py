def record_digest(conn, chat_id, message_text, item_ids, now=None) -> int | None:
    """Транзакционная фиксация отправки (план §1.2): digests + digest_items +
    users.last_sent_at одной транзакцией — защита от дублей при catch-up."""
    now = now or now_iso()
    row = conn.execute(
        "SELECT last_sent_at FROM users WHERE chat_id=%s", (chat_id,)
    ).fetchone()
    if row is None:
        return None
    period_from = row[0] or minus_iso(now, 24)  # первая сводка — окно 24 ч (D9)
    try:
        with conn.transaction():
            cur = conn.execute(
                "INSERT INTO digests (chat_id, period_from, period_to, item_count,"
                " message_text, created_at) VALUES (%s, %s, %s, %s, %s, %s)"
                " RETURNING id",
                (chat_id, period_from, now, len(item_ids), message_text, now),
            )
            digest_id = cur.fetchone()[0]
            executemany(
                conn,
                "INSERT INTO digest_items (digest_id, item_id) VALUES (%s, %s)",
                [(digest_id, item_id) for item_id in item_ids],
            )
            conn.execute(
                "UPDATE users SET last_sent_at=%s WHERE chat_id=%s", (now, chat_id)
            )
    except (sqlite3.IntegrityError, pg_errors.UniqueViolation):
        return None
    return digest_id


