export const SECTION_ORDER = [8, 1, 2, 3, 6, 5, 9, 7, 4, 10, 11, 12];

const DEPTH_TEXT = {
  full: 'полноценно: 3–5 пунктов, у каждого суть и нейро-вывод',
  short: 'коротко: 1–2 пункта одной строкой, без развёрнутого вывода',
};

/** Нумерованный список разделов в нужном порядке — то, что видит LLM. */
export function sectionList(order = SECTION_ORDER) {
  return order
    .map((number) => SECTIONS[Number(number) - 1])
    .filter(Boolean)
    .map((row, index) => {
      const note = row.note ? ` (${row.note})` : '';
      return `${index + 1}. ${row.emoji} ${row.title}${note} — ${DEPTH_TEXT[row.depth] ?? DEPTH_TEXT.full}`;
    })
    .join('\n  ');
}

