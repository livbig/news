const ALLOWED_TAG = /<\/?(b|i)>/gi;

/**
 * Привести ответ LLM к безопасному Telegram-HTML: markdown в теги, теги — только <b>/<i>,
 * внешние ссылки сохраняются лишь из белого списка (иначе разворачиваются в текст).
 */
export function sanitizeFactHtml(raw, allowedUrls = []) {
  const allowed = new Set(allowedUrls.map((url) => String(url).trim()));
  let text = normalizeLlmText(String(raw ?? '')).replace(/```[a-z]*\n?/gi, '');
  // содержимое скриптов не показываем вовсе
  text = text.replace(/<(script|style)[\s\S]*?<\/\1>/gi, ' ');
  // markdown → теги
  text = text.replace(/\*\*([^*\n]+)\*\*/g, '<b>$1</b>').replace(/(^|\s)__([^_\n]+)__(?=\s|$)/g, '$1<i>$2</i>');
  // markdown-ссылки: разрешённые превращаются в <a>, прочие остаются текстом
  text = text.replace(/\[([^\]\n]+)\]\((https?:\/\/[^)\s]+)\)/g, (all, label, url) =>
    allowed.has(url) ? `<a href="${url}">${label}</a>` : label,
  );
  // <pre> со схемой: содержимое экранируем, ширина и число строк ограничены —
  // иначе схема «съезжает» на узком экране телефона.
  const schemes = [];
  text = text.replace(/<pre>([\s\S]*?)<\/pre>/gi, (all, body) => {
    const lines = String(body)
      .replace(/<[^>]*>/g, '')
      .split('\n')
      .map((line) => line.replace(/\s+$/g, '').slice(0, 34))
      .slice(0, 6)
      .join('\n')
      .replace(/^\n+|\n+$/g, '');
    if (!lines) return '';
    schemes.push(escapeHtml(lines));
    return `\u0002${schemes.length - 1}\u0002`;
  });
  // разрешённые ссылки убираем в сторонку, чтобы чистка тегов их не тронула
  const kept = [];
  text = text.replace(/<a\b([^>]*)>([\s\S]*?)<\/a>/gi, (all, attrs, label) => {
    const href = /href="([^"]*)"/i.exec(attrs);
    const url = href ? String(href[1]).trim() : '';
    if (!allowed.has(url)) return label;
    kept.push(`<a href="${url}">${label}</a>`);
    return `\u0000${kept.length - 1}\u0000`;
  });
  // всё, кроме b/i — прочь; висячие <a> без пары — тоже
  text = text.replace(/<(?!\/?(?:b|i)\b)[^>]*>/gi, '');
  text = text.replace(/<(\/?)(b|i)\b[^>]*>/gi, '<$1$2>');
  text = text.replace(/\u0000(\d+)\u0000/g, (all, index) => kept[Number(index)] ?? '');
  text = text.replace(/\u0002(\d+)\u0002/g, (all, index) => (schemes[Number(index)] ? `<pre>${schemes[Number(index)]}</pre>` : ''));
  return text.replace(/\n{3,}/g, '\n\n').trim();
}

const OPTION_LINE = /^\s*(\d)\s*[).]\s*(.+)$/;

/** Разобрать служебный блок «QUIZ/REVIEW … ANSWER … EXPLAIN» → объект квиза. */
function parseQuizBlock(lines, startIndex, label) {
  const options = [];
  let question = '';
  let correct = 0;
  let explanation = '';
  let index = startIndex;
  const first = lines[index].replace(new RegExp(`^${label}\\s*:`), '').trim();
  question = first;
  index += 1;
  for (; index < lines.length; index += 1) {
    const line = lines[index].trim();
    const option = OPTION_LINE.exec(line);
    if (option) {
      options.push(option[2].trim());
      continue;
    }
    const answer = /^ANSWER\s*:\s*(\d)/i.exec(line);
    if (answer) {
      correct = Math.max(0, Number(answer[1]) - 1);
      continue;
    }
    const explain = /^EXPLAIN\s*:\s*(.+)$/i.exec(line);
    if (explain) {
      explanation = explain[1].trim();
      continue;
    }
    if (/^(QUIZ|REVIEW)\s*:/i.test(line)) break;
    if (!line) continue;
    if (!options.length) question += ` ${line}`;
    else break;
  }
  return {
    quiz: { question: question.trim(), options: options.slice(0, 3), correctIndex: Math.min(correct, Math.max(0, options.length - 1)), explanation },
    next: index,
  };
}

/**
 * Разделить ответ модели на текст и квизы: служебные блоки в сообщение не попадают,
 * они уходят настоящими опросами Telegram.
 */
export function parseFactReply(raw) {
  const lines = String(raw ?? '').split('\n');
  const body = [];
  const quiz = [];
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index].trim();
    const label = /^(QUIZ|REVIEW)\s*:/i.exec(line)?.[1]?.toUpperCase();
    if (!label) {
      body.push(lines[index]);
      continue;
    }
    const parsed = parseQuizBlock(lines, index, label);
    if (parsed.quiz.question && parsed.quiz.options.length >= 2) quiz.push({ kind: label === 'REVIEW' ? 'review' : 'today', ...parsed.quiz });
    index = parsed.next - 1;
  }
  return { body: body.join('\n').replace(/\n{3,}/g, '\n\n').trim(), quiz };
}

/** Итоговое сообщение дня: шапка с прогрессом и тема, дальше тело от LLM. */
export function renderDailyFact({ day, entry, body, fallback = false }) {
  const total = COURSE_DAYS;
  const head = `<b>🤖 Physical AI и роботы · день ${day} из ${total}</b>`;
  const block = entry ? `<i>${escapeHtml(entry.block)} — ${escapeHtml(entry.topic)}</i>` : '';
  const practice = entry ? String(entry.practice).replace(/^./, (ch) => ch.toUpperCase()) : '';
  const tail = entry ? `\n\n<i>Слово дня: ${escapeHtml(entry.word)}. ${escapeHtml(practice)}.</i>` : '';
  if (fallback) {
    return `${head}\n${block}\n\n<b>Факт.</b> ${escapeHtml(entry?.topic ?? '')} — сегодня без объяснения: LLM не ответил.\n<b>На практике.</b> ${escapeHtml(entry?.practice ?? '')}.${tail}`;
  }
  return `${head}\n${block}\n\n${body}${tail}`;
}

/**
 * Один прогон рубрики. Возвращает {sent, day} — без побочных эффектов при повторном вызове:
 * за тот же календарный день второй раз не отправляет (ключ слота + дата в состоянии).
 * @param {{chatId:number, slotKey:string|null, todayKey:string, nowMs?:number, deps:{
 *   getState:Function, setState:Function, recentItems:Function, generate:Function,
 *   send:Function, log?:Function}}} options
 */
export async function runDailyFact({ chatId, slotKey = null, todayKey, nowMs = Date.now(), deps }) {
  const { getState, setState, recentItems, generate, send, log = () => {} } = deps;
  if (slotKey && getState(`factslot:${slotKey}`)) return { sent: false, day: null, reason: 'slot' };
  if (todayKey && getState('fact_day_date') === todayKey) return { sent: false, day: null, reason: 'date' };

  const done = Number(getState('fact_day_done') ?? 0) || 0;
  const day = nextFactDay(done);
  if (!day) {
    log(`рубрика: курс ${COURSE_DAYS} дней пройден, дальше не шлю`);
    return { sent: false, day: null, reason: 'finished' };
  }
  const entry = factEntry(day);
  const rows = await recentItems(chatId, nowMs - 24 * 60 * 60 * 1000, 400);
  const items = (rows ?? []).filter(isRoboticsItem).slice(0, 6);

  const reviewEntry = reviewEntryFor(day);
  let body = '';
  let quiz = [];
  try {
    const raw = await generate({ entry, items, reviewEntry });
    const parsed = parseFactReply(raw);
    quiz = parsed.quiz;
    body = sanitizeFactHtml(parsed.body, items.map((item) => item.url));
  } catch (error) {
    log(`рубрика: LLM не ответил (${error?.message ?? error}) — шлю факт без объяснения`);
  }

  const text = renderDailyFact({ day, entry, body, fallback: !body });

  // Визуал: схему из <pre> рисуем картинкой и шлём перед текстом. Не вышло — не беда,
  // схема всё равно останется в тексте, а день не сорвётся из-за картинки.
  const scheme = extractScheme(body);
  if (scheme.length && deps.sendVisual) {
    try {
      await deps.sendVisual(chatId, {
        title: entry ? `День ${day} из ${COURSE_DAYS}: ${entry.topic}` : `День ${day}`,
        subtitle: entry ? `${entry.block} · ${entry.word}` : '',
        lines: scheme,
      });
    } catch (error) {
      log(`рубрика: визуал не отправился (${error?.message ?? error})`);
    }
  }
  // Отправка проверяется: если не ушёл ни один кусок — день не засчитываем и пробуем снова
  // на следующем тике (инцидент 2026-11-14: состояние двигалось, сообщения не было).
  const chunks = await send(chatId, text);
  if (!chunks) {
    log(`рубрика: день ${day} не отправлен (0 кусков) — состояние не двигаю`);
    return { sent: false, day, reason: 'send' };
  }

  // Квизы — настоящими опросами Telegram: ответ проверяется сразу, без сервера.
  if (quiz.length && deps.sendQuiz) {
    for (const item of quiz) {
      try {
        await deps.sendQuiz(chatId, item);
      } catch (error) {
        log(`рубрика: квиз не отправился (${error?.message ?? error})`);
      }
    }
  }

  setState('fact_day_done', String(day));
  setState('last_fact_at', new Date(nowMs).toISOString());
  if (todayKey) setState('fact_day_date', todayKey);
  if (slotKey) setState(`factslot:${slotKey}`, '1');
  return { sent: true, day, chunks };
}
