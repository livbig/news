export const COURSE_DAYS = CURRICULUM.length;

/** Сколько дней уже пройдено → номер следующего дня; null — курс закончен. */
export function nextFactDay(done) {
  const passed = Number(done) || 0;
  return passed < COURSE_DAYS ? passed + 1 : null;
}

export function factEntry(day) {
  return CURRICULUM.find((row) => row.day === Number(day)) ?? null;
}

/** Интервальное повторение: на 4-й день спрашиваем про 1-й, на 5-й — про 2-й и т.д. */
export function reviewEntryFor(day) {
  const back = 3;
  const target = Number(day) - back;
  return target >= 1 ? factEntry(target) : null;
}

/** Пункт ленты о роботах/Physical AI: для блока «новинки рынка» и для контекста. */
export function isRoboticsItem(item) {
  const hay = `${item?.title ?? ''} ${item?.gist ?? ''} ${Array.isArray(item?.topics) ? item.topics.join(' ') : ''}`.toLowerCase();
  return /робот|robot|机器人|人形|humanoid|гуманоид|physical ai|embodied|манипулятор|кобот|cobot|дрон|drone/.test(hay);
}

