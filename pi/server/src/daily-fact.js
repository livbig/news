/** Список пунктов для контекста: только заголовок, выжимка и URL — ссылки проверяемы. */
export function itemsBlock(items) {
  return (items ?? [])
    .slice(0, 6)
    .map((item, index) => {
      const gist = String(item?.gist ?? item?.text ?? '').slice(0, 220).replace(/\s+/g, ' ').trim();
      return `${index + 1}. ${String(item?.title ?? '').trim()} — ${item?.url ?? ''}${gist ? ` — ${gist}` : ''}`;
    })
    .join('\n');
}

